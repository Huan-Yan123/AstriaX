/*
 * 联系方式 —— **一处定义，所有"出了问题找谁"的地方共用**。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ## 为什么要有这个文件（主人 2026-09-27 指出的一处遗漏）
 * ══════════════════════════════════════════════════════════════════════════
 *
 * 他要求「在报错弹窗和设置里附上联系方式 2250713669，标注问题反馈QQ」
 *（后来又加了官方群 1077554004）。
 *
 * 我第一版只在**自研弹窗**（`App.vue` 的 `FEEDBACK_LINE`）和设置页里加了 ——
 * 而**系统原生错误框**（`dialog.showErrorBox`）漏了。
 *
 * 主人实测崩溃时看到的就是原生的「AstriaX 崩溃了」框，
 * 里面**没有联系方式** —— 而那正是最需要联系方式的时刻
 *（软件崩了，用户完全不知道找谁）。
 *
 * ## 为什么放主进程而不是渲染层
 *
 * 原生错误框由**主进程**弹（崩溃时渲染层可能已经没了，
 * 所以它必须走原生弹窗）。而这个常量要给主进程的三处用：
 *   · `crash-handler.ts`      —— 崩溃时的框
 *   · `index.ts` 启动失败       —— 「没能正常打开」的框
 *   · `index.ts` 连续崩溃       —— 「连续崩溃了」的框
 *
 * 渲染层那份（`App.vue` 的 `FEEDBACK_QQ`）**故意独立**：
 * 主进程和渲染层是两个打包域，让渲染层 import 主进程的模块会把
 * 整个模块图搅在一起。**但两处的值必须一致** ——
 * 有一条测试盯着这件事（`tests/unit/feedback-contact.spec.ts`）。
 */

/** 问题反馈 QQ */
export const FEEDBACK_QQ = '2250713669'

/** 官方群 */
export const OFFICIAL_GROUP = '1077554004'

/**
 * 拼给**原生错误框**用的两行联系方式。
 *
 * 原生框是纯文本、不支持富样式，所以这里就用最朴素的两行。
 * 前缀 `——` 是排版习惯：把它和上面的技术信息分开，
 * 让用户在慌乱中也能一眼看到"该找谁"。
 */
export const FEEDBACK_LINES = [
  '',
  `—— 搞不定的话加我 QQ：${FEEDBACK_QQ}（问题反馈QQ）`,
  `—— 也可以加官方群：${OFFICIAL_GROUP}`
].join('\n')
