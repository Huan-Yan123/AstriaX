/*
 * 联系方式 —— **一处定义，所有"出了问题找谁"的地方共用**。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ★★ 只留官方群，去掉个人 QQ（主人 2026-10-08）
 * ══════════════════════════════════════════════════════════════════════════
 *
 * 主人要求：「去掉这个，去掉全部个人 QQ 号，必要的地方替换成群号」。
 *
 * ## 为什么去掉个人 QQ 是对的
 *
 *   · **可持续性**：个人号是"一个人"，问题多了回不过来，
 *     而且那个号一旦不用了，软件里所有联系方式同时失效。
 *     群是"一群人"，老人能带新人，也不依赖某个人在线。
 *   · **心理门槛**：很多人不愿意私聊陌生人，群里问一句压力小得多
 *     （这一点设置页的旧注释里其实已经写过，只是当时两个都留了）。
 *   · **知识沉淀**：同一个问题在群里被问过、被答过，
 *     后来的人搜得到；私聊的答案没人看得见。
 *
 * ## 为什么放主进程而不是渲染层
 *
 * 原生错误框由**主进程**弹（崩溃时渲染层可能已经没了，
 * 所以它必须走原生弹窗）。这个常量要给主进程的三处用：
 *   · `crash-handler.ts`      —— 崩溃时的框
 *   · `index.ts` 启动失败       —— 「没能正常打开」的框
 *   · `index.ts` 连续崩溃       —— 「连续崩溃了」的框
 *
 * 渲染层那份（`App.vue`）**故意独立**：主进程和渲染层是两个打包域，
 * 让渲染层 import 主进程的模块会把整个模块图搅在一起。
 * **但两处的值必须一致** —— 有一条测试盯着这件事
 *（`tests/unit/feedback-contact.spec.ts`）。
 */

