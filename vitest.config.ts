import { defineConfig } from 'vitest/config'
import vue from '@vitejs/plugin-vue'

export default defineConfig({
  plugins: [vue()],
  test: {
    environment: 'happy-dom',
    include: ['tests/**/*.spec.ts'],
    /*
     * ══════════════════════════════════════════════════════════════════════
     * ★★ 文件之间**串行**执行（主人 2026-10-08：全量跑才偶发的红）
     * ══════════════════════════════════════════════════════════════════════
     *
     * 症状：`ipc-handlers` / `stop-really-stops` / `proc-zombie` /
     * `user-reported-bugs` / `instance-status` 这几个文件里，
     * **单独跑全绿、全量跑随机红一条**，报错是
     * "端口 X 已有服务在监听"或"没能确认已停止"，而且每次红的不是同一条。
     *
     * 根因：这些测试会**真的 spawn 子进程并监听端口**（用假命令模拟
     * NapCat/AstrBot 起来的样子）。vitest 默认让多个测试文件**并行**跑，
     * 于是：
     *   · 文件 A 起的假实例还占着 6200
     *   · 文件 B 的 `freePortIn(6200,6299)` 从区间头扫，选到它
     *   · 被测代码在 `instance:start` 里探到"端口已有服务" → 拒绝启动 → 红
     *
     * 子进程退出有延迟，所以是否撞上**取决于调度时序** —— 这正是
     * "看运气"的那类红，最难查（本项目已经为它反复消耗过好几轮）。
     *
     * ## 为什么用串行而不是继续调各文件的端口
     *
     * 试过两条路都不行：
     *   · 给单个用例换端口段 → 冲突被推到**同一个文件的下一条**用例
     *   · 在 afterEach 里统一杀进程 → 把用例**中途**要用进程的场景搞坏
     *     （比如"进程退出后仍按端口判活"那条，进程必须活到断言前）
     *
     * 而根因是"**跨文件共享系统资源（端口/进程）**"，那么正确的解法就是
     * 不让它们并行 —— 这类测试本来就不该并行跑。
     *
     * 代价：全量耗时变长（实测约 3 分钟，可接受）。
     * 收益：消除一整类假红。假红的危害不只是浪费时间 ——
     * 它会让人**不再相信测试结果**，真出问题时也被当成"又是那个偶发"。
     */
    fileParallelism: false
  }
})
